import sys, json, time
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/index.html"
EXE = "/opt/pw-browsers/chromium-1243/chrome-linux64/chrome"
SHOTS = sys.argv[2] if len(sys.argv) > 2 else None

problems = []
passed = 0

def check(cond, msg):
    global passed
    if cond:
        passed += 1
        print("  ok  ", msg)
    else:
        problems.append(msg)
        print("  FAIL", msg)

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path=EXE, args=["--no-sandbox"])
    ctx = browser.new_context(viewport={"width": 1440, "height": 900}, color_scheme="dark")
    page = ctx.new_page()
    errors = []
    page.on("console", lambda m: errors.append(f"console.{m.type}: {m.text}") if m.type in ("error", "warning") else None)
    page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    page.on("requestfailed", lambda r: errors.append(f"requestfailed: {r.url}"))
    page.on("response", lambda r: errors.append(f"http {r.status}: {r.url}") if r.status >= 400 else None)

    print("Home")
    page.goto(BASE)
    page.wait_for_selector("#homeDemo .tile")
    txt = page.inner_text("#page-home")
    for needle in ["Artificial Intelligence", "Interactive 8-Puzzle Problem Solver using AI Search Algorithms", "Bonam Pavanji", "24BCI0083"]:
        check(needle in txt, f"home shows '{needle}'")
    check(page.locator(".app-nav .nav-link").count() == 4, "navigation has 4 links")
    check(page.locator("#homeDemo .tile").count() == 8, "home demo board has 8 tiles")
    if SHOTS: page.screenshot(path=f"{SHOTS}/home.png")

    def goto(route):
        page.click(f'.app-nav .nav-link[data-route="{route}"]')
        page.wait_for_selector(f"#page-{route}:not([hidden])")

    print("Solver: structure")
    goto("solver")
    check(page.locator("#startInputs input").count() == 9 and page.locator("#goalInputs input").count() == 9, "two 3x3 input grids")
    vals = page.eval_on_selector_all("#startInputs input", "els => els.map(e => e.value).join('')")
    check(vals == "283164_05".replace("_", "_") or vals == "2831647_5", f"initial grid preloaded with example ({vals})")
    check("Valid and solvable" in page.inner_text("#puzzleStatus"), "example is reported valid and solvable")
    check(page.input_value("#algoSelect") == "dfs", "DFS (assigned) selected by default")
    opts = page.eval_on_selector_all("#algoSelect option", "els => els.map(e => e.value)")
    check(opts[:6] == ["bfs", "dfs", "dls", "iddls", "gbfs", "astar"], f"six required algorithms in order {opts}")
    check(page.locator("#depthWrap").is_hidden(), "depth limit hidden for DFS")
    check(page.locator("#heurWrap").is_hidden(), "heuristic hidden for DFS")
    check(page.locator("#tileH").is_hidden(), "h(n) tile hidden for DFS")
    for sel in ["#btnRun", "#btnPause", "#btnResume", "#btnNext", "#btnPrev", "#btnReset"]:
        check(page.locator(sel).count() == 1, f"control {sel} exists")
    check(page.locator("#btnPause").is_disabled() and page.locator("#btnPrev").is_disabled() and page.locator("#btnResume").is_disabled(), "pause/resume/prev disabled before run")

    print("Solver: option visibility")
    page.select_option("#algoSelect", "dls")
    check(page.locator("#depthWrap").is_visible(), "depth limit visible for DLS")
    page.select_option("#algoSelect", "gbfs")
    check(page.locator("#heurWrap").is_visible() and page.locator("#tileH").is_visible() and page.locator("#tileF").is_visible(), "heuristic + h/f tiles visible for GBFS")
    page.select_option("#algoSelect", "astar")
    check(page.locator("#heurWrap").is_visible(), "heuristic visible for A*")
    page.select_option("#algoSelect", "dfs")

    print("Solver: DFS run and controls")
    page.click("#btnRun")
    page.wait_for_function("window.Solver.state.timeline !== null", timeout=30000)
    page.wait_for_timeout(600)
    check(page.locator("#btnPause").is_enabled(), "pause enabled while playing")
    check(page.locator("#phaseBadge").text_content() in ("Searching", "Goal reached", "Replaying solution"), "phase badge updates while running")
    page.click("#btnPause")
    s1 = page.evaluate("window.Solver.state.idx")
    check(page.locator("#btnResume").is_enabled(), "resume enabled after pause")
    page.wait_for_timeout(500)
    s2 = page.evaluate("window.Solver.state.idx")
    check(s1 == s2, f"paused: step index frozen ({s1})")
    page.click("#btnNext")
    s3 = page.evaluate("window.Solver.state.idx")
    check(s3 == s1 + 1, f"next step advances by one ({s1}->{s3})")
    page.click("#btnPrev")
    s4 = page.evaluate("window.Solver.state.idx")
    check(s4 == s1, f"previous step goes back one ({s3}->{s4})")
    page.click("#btnResume")
    page.wait_for_timeout(400)
    s5 = page.evaluate("window.Solver.state.idx")
    check(s5 > s1 or page.evaluate("window.Solver.state.idx") >= page.evaluate("window.Solver.state.timeline.length-1"), "resume continues playback")
    page.click("#btnPause") if page.locator("#btnPause").is_enabled() else None

    page.click("#btnEnd")
    page.wait_for_selector("#summary .verdict")
    check("Solution Found" in page.inner_text("#summary"), "summary: Solution Found")
    for label in ["Total moves", "Nodes generated", "Nodes expanded", "Maximum search depth", "Execution time", "Path cost", "Memory"]:
        check(label.lower() in page.inner_text("#summary").lower(), f"summary shows {label}")
    res = page.evaluate("({n: window.Solver.state.result.moves.length, f: window.Solver.state.result.found})")
    check(res["f"] and res["n"] >= 5, f"DFS found a path of {res['n']} moves (>=5)")
    check(page.locator(".step-card").count() >= 2, "solution path cards rendered")
    last_state = page.evaluate("(() => {const S=window.Solver.state; return S.timeline[S.timeline.length-1].state})()")
    check(last_state == "123804765", "final replay state equals the goal")
    st = page.inner_text("#stExpanded").replace(",", "")
    exp = page.evaluate("window.Solver.state.result.stats.expanded")
    check(int(st) == exp, f"live expanded counter ends at the true total ({exp})")
    check("shortest solution is only" in page.inner_text("#summary") or "matches the shortest" in page.inner_text("#summary"), "DFS summary compares against optimal")
    if SHOTS: page.screenshot(path=f"{SHOTS}/solver-dfs-done.png", full_page=True)

    print("Solver: Reset")
    page.click("#btnReset")
    check(page.evaluate("window.Solver.state.timeline") is None, "reset clears the run")
    check("Results appear" in page.inner_text("#summary"), "reset clears the summary")
    check(page.inner_text("#stGenerated") == "0", "reset zeroes counters")

    print("Solver: every algorithm on the brief's example (optimal length 5)")
    expected = {"bfs": 5, "iddls": 5, "astar": 5, "ucs": 5}
    for algo in ["bfs", "dfs", "dls", "iddls", "gbfs", "astar", "ucs"]:
        page.select_option("#algoSelect", algo)
        if algo == "dls":
            page.fill("#depthLimit", "5")
        page.click("#btnRun")
        page.wait_for_function("window.Solver.state.timeline !== null", timeout=60000)
        page.click("#btnEnd")
        page.wait_for_selector("#summary .verdict")
        r = page.evaluate("({f: window.Solver.state.result.found, n: window.Solver.state.result.moves.length, s: window.Solver.state.result.status})")
        check(r["f"], f"{algo}: solution found ({r['n']} moves)")
        if algo in expected:
            check(r["n"] == 5, f"{algo}: optimal 5 moves")
        shown = page.inner_text("#summary .sum-grid .stat:first-child .stat-n").replace(",", "")
        check(shown == str(r["n"]), f"{algo}: summary moves matches result")

    print("Solver: DLS failure + informed stats")
    page.select_option("#algoSelect", "dls")
    page.fill("#depthLimit", "4")
    page.dispatch_event("#depthLimit", "change")
    page.click("#btnRun")
    page.wait_for_function("window.Solver.state.timeline !== null")
    page.click("#btnEnd")
    page.wait_for_selector("#summary .verdict")
    check("Solution Not Found" in page.inner_text("#summary"), "DLS depth 4: Solution Not Found")
    check("depth limit 4" in page.inner_text("#summary"), "DLS failure explains the depth limit")
    check(page.locator("#phaseBadge").text_content() == "No solution", "phase badge says No solution")

    page.select_option("#algoSelect", "astar")
    page.click("#heurMisplaced", force=True)
    page.click("#btnRun")
    page.wait_for_function("window.Solver.state.timeline !== null")
    page.click("#btnPause") if page.locator("#btnPause").is_enabled() else None
    page.evaluate("window.Solver.state.idx = 0")
    page.click("#btnNext"); page.click("#btnNext")
    hv = page.inner_text("#stH"); fv = page.inner_text("#stF"); gv = page.inner_text("#stG")
    check(hv.isdigit() and fv.isdigit() and gv.isdigit() and int(fv) == int(gv) + int(hv), f"A*: f = g + h shown live (g={gv}, h={hv}, f={fv})")
    check(page.locator("#frontierList .node").count() >= 1, "frontier list populated")
    check(page.locator("#childrenList .node").count() >= 1, "successor states shown")
    if SHOTS: page.screenshot(path=f"{SHOTS}/solver-astar-step.png", full_page=True)

    print("Solver: input validation")
    page.click("#btnReset")
    page.fill("#startInputs input >> nth=0", "")
    page.fill("#startInputs input >> nth=0", "1")
    check("not valid" in page.inner_text("#puzzleStatus").lower(), "duplicate tile flagged invalid")
    check(page.locator("#startInputs input.bad").count() >= 2, "duplicate cells highlighted")
    page.click("#btnExample")
    check("Valid and solvable" in page.inner_text("#puzzleStatus"), "example button restores a valid puzzle")
    page.fill("#startInputs input >> nth=0", "8")
    page.fill("#startInputs input >> nth=1", "2")
    check("unsolvable" in page.inner_text("#puzzleStatus").lower(), "unsolvable puzzle detected")
    check(page.locator("#btnFixSolvable").is_visible(), "fix button offered")
    page.click("#btnFixSolvable")
    check("Valid and solvable" in page.inner_text("#puzzleStatus"), "fix button makes it solvable")
    page.click("#btnExample")
    page.fill("#startInputs input >> nth=3", "9")
    check(page.input_value("#startInputs input >> nth=3") == "", "invalid character 9 rejected")
    page.click("#btnExample")
    page.fill("#startInputs input >> nth=7", "0")
    check(page.input_value("#startInputs input >> nth=7") == "_", "0 becomes the blank")

    print("Solver: random generation")
    ok_all = True
    for d in ["easy", "medium", "hard", "random"]:
        page.select_option("#difficulty", d)
        for _ in range(8):
            page.click("#btnRandom")
            ok_all = ok_all and ("Valid and solvable" in page.inner_text("#puzzleStatus") or "already equals" in page.inner_text("#puzzleStatus"))
    check(ok_all, "32 generated puzzles all valid + solvable")
    page.click("#btnStdGoal")
    page.click("#btnRandom")
    check("Valid and solvable" in page.inner_text("#puzzleStatus"), "random puzzle solvable for the standard goal too")
    page.click("#btnSnailGoal")
    if "unsolvable" in page.inner_text("#puzzleStatus").lower():
        page.click("#btnRandom")
    check("Valid and solvable" in page.inner_text("#puzzleStatus"), "random puzzle solvable for the snail goal")

    print("Solver: speed + scrubber")
    page.click("#btnExample")
    page.select_option("#algoSelect", "bfs")
    page.fill("#speed", "10")
    page.dispatch_event("#speed", "input")
    check("400" in page.inner_text("#speedLabel"), "speed slider updates label")
    page.click("#btnRun")
    page.wait_for_function("window.Solver.state.timeline !== null")
    page.wait_for_function("window.Solver.state.idx >= window.Solver.state.timeline.length - 1", timeout=20000)
    check(page.locator("#btnResume").is_disabled(), "resume disabled at the end")
    page.fill("#scrub", "3")
    page.dispatch_event("#scrub", "input")
    check(page.evaluate("window.Solver.state.idx") == 3, "scrubber jumps to a step")
    page.keyboard.press("Escape")

    print("Compare page")
    page.click("#btnExample")
    goto("compare")
    page.fill("#cmpDepth", "5")
    page.click("#btnCmpRun")
    page.wait_for_function("document.querySelectorAll('#cmpBody tr').length >= 7 && !document.querySelector('#cmpBody .empty')", timeout=60000)
    rows = page.eval_on_selector_all("#cmpBody tr", "trs => trs.map(tr => Array.from(tr.children).map(td => td.innerText.replace(/\\s+/g,' ').trim()))")
    check(len(rows) == 7, f"comparison table has 7 rows ({len(rows)})")
    byname = {r[0].split(' ')[0]: r for r in rows}
    check(byname["BFS"][4].replace(" ★", "") == "5", f"BFS moves 5 in table ({byname['BFS'][4]})")
    check(byname["A*"][4].replace(" ★", "") == "5", "A* moves 5 in table")
    check("Yes" in byname["DLS"][1], "DLS depth 5 finds solution in table")
    check(page.locator("#cmpCharts .bar-row").count() >= 15, "bar charts rendered")
    check("shortest solution has" in page.inner_text("#cmpNote"), "insight note generated")
    page.select_option("#cmpHeur", "both")
    page.click("#btnCmpRun")
    page.wait_for_function("document.querySelectorAll('#cmpBody tr').length === 9", timeout=60000)
    check(page.locator("#cmpBody tr").count() == 9, "both heuristics adds two rows")
    page.fill("#cmpDepth", "3")
    page.click("#btnCmpRun")
    page.wait_for_function("document.querySelectorAll('#cmpBody tr').length === 9 && !document.getElementById('btnCmpRun').disabled", timeout=60000)
    dls = [r for r in page.eval_on_selector_all("#cmpBody tr", "trs => trs.map(tr => Array.from(tr.children).map(td => td.innerText.replace(/\\s+/g,' ').trim()))") if r[0].startswith("DLS")][0]
    check("No" in dls[1] and dls[4] == "–", f"DLS depth 3 shows No and '–' moves ({dls[1]}, {dls[4]})")
    check("Raise the limit" in page.inner_text("#cmpNote"), "note advises raising the DLS limit")
    page.select_option("#cmpHeur", "manhattan")
    page.click("#btnCmpRandom")
    check("New random puzzle" in page.inner_text("#cmpStatus"), "new random puzzle from compare page")
    if SHOTS:
        goto("solver"); page.click("#btnExample"); goto("compare")
        page.fill("#cmpDepth", "5")
        page.click("#btnCmpRun")
        page.wait_for_function("!document.getElementById('btnCmpRun').disabled && document.querySelectorAll('#cmpBody tr').length>=7 && !document.querySelector('#cmpBody .empty')", timeout=60000)
        page.screenshot(path=f"{SHOTS}/compare.png", full_page=True)

    print("Algorithms page")
    goto("algorithms")
    check(page.locator("#algoTabs .nav-link").count() == 7, "7 algorithm tabs")
    for a in ["bfs", "dfs", "dls", "iddls", "gbfs", "astar", "ucs"]:
        page.click(f"#tab-{a}")
        t = page.text_content("#algoDetail")
        ok = all(k in t for k in ["Description", "Working principle", "Advantages", "Limitations", "Time complexity", "Space complexity", "Completeness", "Optimality"])
        check(ok, f"{a}: all eight required sections present")
    page.click("#tab-dfs")
    check("24BCI0083" in page.inner_text("#algoDetail"), "DFS tab marked as assigned")
    check(page.locator("#heuristicCards .formula").count() == 2, "two heuristics documented")
    if SHOTS: page.screenshot(path=f"{SHOTS}/algorithms.png", full_page=True)

    print("Try-in-solver link + routing")
    page.click("#tab-astar")
    page.click("#algoDetail [data-algo]")
    page.wait_for_selector("#page-solver:not([hidden])")
    check(page.input_value("#algoSelect") == "astar", "link preselects the algorithm")
    page.goto(BASE + "#nonsense")
    page.wait_for_selector("#page-home:not([hidden])")
    check(True, "unknown route falls back to home")

    print("Theme")
    page.click("#themeToggle")
    check(page.evaluate("document.documentElement.getAttribute('data-bs-theme')") == "light", "theme toggles to light")
    page.goto(BASE + "#solver")
    page.wait_for_selector("#page-solver:not([hidden])")
    if SHOTS: page.screenshot(path=f"{SHOTS}/solver-light.png", full_page=True)
    page.click("#themeToggle")

    print("Responsive (390x844)")
    m = browser.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, has_touch=True, is_mobile=True, color_scheme="dark")
    mp = m.new_page()
    merrs = []
    mp.on("pageerror", lambda e: merrs.append(str(e)))
    mp.on("console", lambda x: merrs.append(x.text) if x.type == "error" else None)
    for route in ["home", "solver", "compare", "algorithms"]:
        mp.goto(BASE + "#" + route)
        mp.wait_for_selector(f"#page-{route}:not([hidden])")
        mp.wait_for_timeout(250)
        sw = mp.evaluate("document.documentElement.scrollWidth")
        check(sw <= 392, f"mobile {route}: no horizontal overflow (scrollWidth {sw})")
        if SHOTS: mp.screenshot(path=f"{SHOTS}/mobile-{route}.png", full_page=(route != "solver"))
    mp.goto(BASE + "#solver")
    mp.wait_for_selector("#page-solver:not([hidden])")
    mp.click("#btnRunMain")
    mp.wait_for_function("window.Solver.state.timeline !== null", timeout=30000)
    mp.click("#btnEnd")
    mp.wait_for_selector("#summary .verdict")
    sw = mp.evaluate("document.documentElement.scrollWidth")
    check(sw <= 392, f"mobile solver after run: no horizontal overflow (scrollWidth {sw})")
    if SHOTS: mp.screenshot(path=f"{SHOTS}/mobile-solver-done.png", full_page=True)
    check(not merrs, f"mobile: no console errors {merrs[:2]}")

    check(not errors, f"no console errors / failed requests: {errors[:4]}")
    browser.close()

print(f"\n{passed} checks passed, {len(problems)} failed")
for p in problems: print(" -", p)
sys.exit(1 if problems else 0)
